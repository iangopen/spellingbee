// Runs contrast.html headless (straight from disk) and writes contrast.json and contrast.md.
//   PW_MODULE=<playwright/index.mjs> node design/prototypes/avatar-maker/measure-contrast.mjs [out-prefix]
// The out-prefix defaults to "contrast" (contrast.json / contrast.md next to this file).
import { pathToFileURL, fileURLToPath } from "node:url";
import { writeFileSync } from "node:fs";
import path from "node:path";
const { chromium } = await import(pathToFileURL(process.env.PW_MODULE).href);
const here = path.dirname(fileURLToPath(import.meta.url));
const prefix = process.argv[2] ?? "contrast";

const b = await chromium.launch();
try {
  const p = await b.newPage();
  const errors = [];
  p.on("pageerror", (e) => errors.push(e.message));
  await p.goto(pathToFileURL(path.join(here, "contrast.html")).href);
  await p.waitForSelector("body[data-done]", { timeout: 120000 });
  const res = await p.evaluate(() => window.__contrast);
  if (!res || errors.length) throw new Error("contrast page failed: " + errors.join(" | "));
  writeFileSync(path.join(here, `${prefix}.json`), JSON.stringify(res, null, 1));

  const sets = { playful: "Playful", spelling: "Spelling-themed" };
  let md = `# Avatar silhouette contrast (${prefix})\n\nGenerated by \`measure-contrast.mjs\` from \`contrast.html\`. ${res.method}. ` +
    `Each cell is the worst of the three backgrounds; 3:1 needed (WCAG 1.4.11). **${res.failures.length} failures** in 256 measurements.\n`;
  for (const [theme, T] of Object.entries(res.themes)) {
    md += `\n## ${theme} theme\n\nBackgrounds: ${T.backgrounds.map((x) => `${x.label} \`${x.hex}\``).join("; ")}.\n`;
    for (const [set, cells] of Object.entries(T.sets)) {
      const names = [...new Set(cells.map((c) => c.cosmetic))];
      md += `\n### ${sets[set]}\n\n| Colour | ${names.join(" | ")} |\n|---|${names.map(() => "---:").join("|")}|\n`;
      for (let c = 0; c < 8; c++) md += `| ${cells[c * 8].color} | ${cells.slice(c * 8, c * 8 + 8).map((x) => (x.worst < 3 ? `**${x.worst.toFixed(2)} ✗**` : x.worst.toFixed(2))).join(" | ")} |\n`;
    }
    md += `\nBody against the outline (--bee-line): ${T.bodyVsOutline.map((x) => `${x.color} ${x.ratio}`).join(", ")}.\n`;
    md += T.halo
      ? `\nToken halo \`--av-halo\` ${T.halo.hex} (1 CSS px; ${T.halo.radiiRasterPx.join(" and ")} raster px at the 30 and 140 px boxes) against the backgrounds: ${T.halo.vs.map((x) => `${x.bg} ${x.ratio}`).join(", ")}.\n`
      : `\nNo token halo in this theme (\`--av-halo\` is transparent).\n`;
    md += `\nAntennae (--bee-line) against the backgrounds, as lines on their own: ${T.antennae.map((x) => `${x.bg} ${x.ratio}`).join(", ")}.\n`;
  }
  if (res.failures.length) {
    md += `\n## Failures\n\n| Theme | Set | Colour | Cosmetic | Worst | Background | At (viewBox) |\n|---|---|---|---|---:|---|---|\n`;
    for (const f of res.failures) md += `| ${f.theme} | ${f.set} | ${f.color} | ${f.cosmetic} | ${f.worst} | ${f.bg} | ${f.at.join(", ")} |\n`;
  }
  writeFileSync(path.join(here, `${prefix}.md`), md);
  console.log(`${res.failures.length} failures, ${res.ms} ms`);
  for (const f of res.failures) console.log(`  ${f.theme} ${f.set} ${f.color} + ${f.cosmetic}: ${f.worst} on ${f.bg} at ${f.at}`);
  for (const [theme, T] of Object.entries(res.themes)) console.log(`  ${theme} antennae: ${T.antennae.map((x) => `${x.bg} ${x.ratio}`).join(", ")}`);
} finally {
  await b.close();
}
